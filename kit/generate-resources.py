#!/usr/bin/env python3
"""Generate relocatable SVG string tables; --check verifies checked-in output."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent / "qml" / "Hensou"
output = "// Generated by kit/generate-resources.py. Do not edit.\n.pragma library\n"
for theme in ("platinum", "win98"):
    icons = {p.stem: p.read_text() for p in sorted((root / "assets" / theme).glob("*.svg"))}
    output += "var " + theme + " = " + json.dumps(icons, ensure_ascii=True, indent=2) + ";\n"
target = root / "resources.js"
if args.check:
    if target.read_text() != output:
        raise SystemExit("resources.js is stale; run python3 kit/generate-resources.py")
    print("HENSOU_RESOURCES_PASSED")
else:
    target.write_text(output)
